USE BIBLIOTECA;
SELECT TITULO,AUTOR_ID
FROM LIBROS;

SELECT TITULO
FROM LIBROS
WHERE EDITORIAL_ID=2;

SELECT NOMBRE
FROM AUTORES
ORDER BY NOMBRE DESC;

SELECT l.TITULO,a.NOMBRE
FROM LIBROS l
INNER JOIN AUTORES a
ON l.AUTOR_ID=a.AUTOR_ID
ORDER BY NOMBRE DESC;

SELECT l.TITULO,tl.FECHA,tl.MIEMBRO_ID
FROM transacciones_libros tl
INNER JOIN LIBROS l
ON l.LIBROS_ID=tl.LIBROS_ID
WHERE tl.FECHA>'2025-02-02'
AND tl.MIEMBRO_ID =111;

